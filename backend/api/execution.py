"""
DataPilot OS — Execution API Router.
Runs validated code in isolated sandbox. Never executes unvalidated code.
Execution states: QUEUED → VALIDATING → RUNNING → SUCCEEDED/FAILED/TIMED_OUT
"""
import logging
from typing import Dict, Any, Optional
from fastapi import APIRouter, HTTPException
from fastapi.responses import JSONResponse
from pydantic import BaseModel

logger = logging.getLogger(__name__)

router = APIRouter(prefix="/api/execution", tags=["execution"])

try:
    from backend.execution.runner import execution_runner
    from backend.execution.artifacts import artifact_manager
    from backend.core.dataset_registry import dataset_registry
    EXECUTION_AVAILABLE = True
except ImportError as e:
    logger.error(f"Execution engine import failed: {e}")
    EXECUTION_AVAILABLE = False


class DirectRunRequest(BaseModel):
    code: Optional[str] = None
    code_version_id: Optional[str] = None
    dataset_id: Optional[str] = None
    workflow_id: Optional[str] = None
    node_id: Optional[str] = None


@router.post("/run")
@router.post("/execute")
def run_code(request: DirectRunRequest):
    """Execute code in isolated subprocess sandbox with active dataset context."""
    df = None
    if request.dataset_id and dataset_registry:
        try:
            df = dataset_registry.get_dataframe(request.dataset_id)
        except Exception as ds_err:
            logger.warning(f"Failed to fetch dataset {request.dataset_id}: {ds_err}")

    if df is None and dataset_registry and hasattr(dataset_registry, 'get_active'):
        active_ds = dataset_registry.get_active()
        if active_ds:
            if hasattr(active_ds, 'dataset_id'):
                df = dataset_registry.get_dataframe(active_ds.dataset_id)
            elif hasattr(active_ds, 'df') and active_ds.df is not None:
                df = active_ds.df

    if df is None:
        # The canonical DatasetRegistry is the only supported source of a
        # dataframe.  Falling back to legacy module-global state allowed a
        # manual execution request to operate on an unrelated/stale dataset
        # after a dataset switch.  Fail explicitly instead of importing the
        # retired router's state.
        raise HTTPException(
            status_code=409,
            detail="No active dataset in DatasetRegistry. Select or provide a dataset_id before executing code.",
        )

    code_to_run = request.code
    if not code_to_run and request.code_version_id:
        try:
            from backend.api.code import _code_versions
            code_ver = _code_versions.get(request.code_version_id)
            if code_ver:
                code_to_run = getattr(code_ver, 'code', None)
        except Exception:
            pass

    if not code_to_run:
        raise HTTPException(status_code=400, detail="No Python code provided for execution.")

    try:
        from modules.execution_engine import ModularExecutionEngine
        exec_engine = ModularExecutionEngine()
        res = exec_engine.execute_code_subprocess(code_to_run, df=df)

        return {
            "status": "success" if res.get("success", True) else "execution_error",
            "output": res.get("stdout") or res.get("output") or "Code executed cleanly.",
            "plot_image": res.get("plot_image"),
            "error": res.get("stderr") or res.get("error")
        }
    except Exception as err:
        logger.error(f"EXECUTION_RUN_ERROR: {err}", exc_info=True)
        return {
            "status": "execution_error",
            "output": None,
            "plot_image": None,
            "error": str(err)
        }


@router.get("/{execution_id}")
async def get_execution_status(execution_id: str):
    """Get current execution status and result."""
    if not EXECUTION_AVAILABLE:
        raise HTTPException(status_code=503, detail="Execution engine not available")
    record = execution_runner.get_status(execution_id)
    if not record:
        raise HTTPException(status_code=404, detail=f"Execution '{execution_id}' not found")
    return record.model_dump()


@router.post("/{execution_id}/stop")
async def stop_execution(execution_id: str):
    """Cancel a running execution."""
    if not EXECUTION_AVAILABLE:
        raise HTTPException(status_code=503, detail="Execution engine not available")
    success = execution_runner.cancel(execution_id)
    return {"status": "cancelled" if success else "not_found", "execution_id": execution_id}


@router.get("/{execution_id}/artifacts")
async def get_artifacts(execution_id: str):
    """Get all artifacts generated by an execution (plots, tables, metrics)."""
    if not EXECUTION_AVAILABLE:
        return []
    artifacts = artifact_manager.get_for_execution(execution_id)
    return [a.model_dump() for a in artifacts]
