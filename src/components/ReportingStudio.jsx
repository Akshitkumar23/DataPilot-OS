import React, { useState, useEffect, useCallback } from 'react';
import {
  FileText, Download, Printer, RefreshCw, AlertTriangle, CheckCircle2,
  Database, Activity, BarChart2, Brain, TrendingUp, Layers, HelpCircle,
  ChevronRight, ExternalLink, ShieldCheck, Clock, Award
} from 'lucide-react';
import { API, getAuthHeaders } from '../apiConfig';

export default function ReportingStudio({ activeDataset }) {
  const [report, setReport] = useState(null);
  const [evidencePackage, setEvidencePackage] = useState(null);
  const [isGenerating, setIsGenerating] = useState(false);
  const [isLoadingEvidence, setIsLoadingEvidence] = useState(false);
  const [selectedSection, setSelectedSection] = useState('overview');
  const [errorMessage, setErrorMessage] = useState(null);

  // 1. Fetch Harvested Evidence
  const fetchEvidence = useCallback(async () => {
    if (!activeDataset?.id) return;
    setIsLoadingEvidence(true);
    setErrorMessage(null);
    try {
      const res = await fetch(`${API}/api/reports/evidence?dataset_id=${encodeURIComponent(activeDataset.id)}`, {
        headers: getAuthHeaders(),
      });
      if (res.ok) {
        const data = await res.json();
        setEvidencePackage(data);
      }
    } catch (err) {
      console.error('Failed to load report evidence:', err);
    } finally {
      setIsLoadingEvidence(false);
    }
  }, [activeDataset]);

  // 2. Fetch Latest Generated Report
  const fetchLatestReport = useCallback(async () => {
    if (!activeDataset?.id) return;
    try {
      const res = await fetch(`${API}/api/reports/latest?dataset_id=${encodeURIComponent(activeDataset.id)}`, {
        headers: getAuthHeaders(),
      });
      if (res.ok) {
        const data = await res.json();
        if (data && data.report_id) {
          setReport(data);
        }
      }
    } catch (err) {
      console.warn('Could not load latest report:', err);
    }
  }, [activeDataset]);

  useEffect(() => {
    fetchEvidence();
    fetchLatestReport();
  }, [fetchEvidence, fetchLatestReport]);

  // 3. Generate Analytical Report
  const handleGenerateReport = async () => {
    if (!activeDataset?.id) return;
    setIsGenerating(true);
    setErrorMessage(null);

    try {
      const res = await fetch(`${API}/api/reports/generate`, {
        method: 'POST',
        headers: getAuthHeaders({ 'Content-Type': 'application/json' }),
        body: JSON.stringify({
          dataset_id: activeDataset.id,
          title: `Analytical Synthesis Report — ${activeDataset.name || 'Dataset'}`,
          executive_notes: 'Comprehensive multi-phase analytical synthesis report generated by DataPilot OS.',
        }),
      });

      const data = await res.json();
      if (res.ok && data.report_id) {
        setReport(data);
        fetchEvidence();
      } else {
        setErrorMessage(data.detail || 'Failed to generate analytical report.');
      }
    } catch (err) {
      setErrorMessage(`Report generation error: ${err.message}`);
    } finally {
      setIsGenerating(false);
    }
  };

  // 4. Export Standalone HTML
  const handleExportHtml = async () => {
    if (!activeDataset?.id) return;
    try {
      const res = await fetch(`${API}/api/reports/export?dataset_id=${encodeURIComponent(activeDataset.id)}`, {
        headers: getAuthHeaders(),
      });
      if (res.ok) {
        const blob = await res.blob();
        const url = window.URL.createObjectURL(blob);
        const a = document.createElement('a');
        a.href = url;
        a.download = `analytical_report_${activeDataset.name || 'dataset'}_${Date.now()}.html`;
        document.body.appendChild(a);
        a.click();
        document.body.removeChild(a);
      } else {
        alert('Please generate a report first before exporting.');
      }
    } catch (err) {
      alert(`Export failed: ${err.message}`);
    }
  };

  // 5. Print Preview / Window Print
  const handlePrint = async () => {
    if (!activeDataset?.id) return;
    try {
      const res = await fetch(`${API}/api/reports/export?dataset_id=${encodeURIComponent(activeDataset.id)}`, {
        headers: getAuthHeaders(),
      });
      if (res.ok) {
        const html = await res.text();
        const printWindow = window.open('', '_blank');
        if (printWindow) {
          printWindow.document.write(html);
          printWindow.document.close();
          setTimeout(() => {
            printWindow.focus();
            printWindow.print();
          }, 400);
        }
      }
    } catch (err) {
      window.print();
    }
  };

  const sectionsList = [
    { id: 'overview', title: '1. Dataset Overview', icon: Database },
    { id: 'governance', title: '2. Data Governance & Lineage', icon: ShieldCheck },
    { id: 'eda', title: '3. Exploratory Analysis', icon: Activity },
    { id: 'statistics', title: '4. Statistical Inferences', icon: BarChart2 },
    { id: 'ml', title: '5. Machine Learning', icon: Brain },
    { id: 'unsupervised', title: '6. Clustering & PCA', icon: Layers },
    { id: 'timeseries', title: '7. Time-Series Analysis', icon: TrendingUp },
    { id: 'sql', title: '8. Governed DuckDB SQL', icon: Database },
    { id: 'limitations', title: '9. Limitations & Caveats', icon: HelpCircle },
  ];

  const currentSectionData = report?.sections?.find(s => s.section_id === selectedSection);

  return (
    <div style={{
      display: 'flex',
      flexDirection: 'column',
      height: '100%',
      width: '100%',
      background: '#090d16',
      color: '#f8fafc',
      fontFamily: 'Inter, system-ui, sans-serif',
      overflow: 'hidden'
    }}>
      {/* 1. Header Toolbar */}
      <div style={{
        padding: '14px 20px',
        background: '#0f172a',
        borderBottom: '1px solid #1e293b',
        display: 'flex',
        alignItems: 'center',
        justifyContent: 'space-between',
        flexShrink: 0
      }}>
        <div style={{ display: 'flex', alignItems: 'center', gap: 12 }}>
          <div style={{ background: '#0284c7', padding: 8, borderRadius: 8, display: 'flex' }}>
            <FileText size={20} color="#ffffff" />
          </div>
          <div>
            <div style={{ display: 'flex', alignItems: 'center', gap: 8 }}>
              <h2 style={{ margin: 0, fontSize: 16, fontWeight: 800, color: '#f8fafc' }}>
                Analytical Reporting Studio
              </h2>
              {evidencePackage?.stale_warning && (
                <span style={{
                  background: '#422006', color: '#fde047', fontSize: 10, fontWeight: 700,
                  padding: '2px 8px', borderRadius: 4, display: 'flex', alignItems: 'center', gap: 4
                }}>
                  <AlertTriangle size={12} /> Stale Evidence Detected
                </span>
              )}
            </div>
            <p style={{ margin: 0, fontSize: 11, color: '#94a3b8' }}>
              Synthesizes real, verified evidence across Profiling, Statistics, ML, Time-Series, and DuckDB SQL.
            </p>
          </div>
        </div>

        {/* Action Controls */}
        <div style={{ display: 'flex', alignItems: 'center', gap: 10 }}>
          <button
            onClick={fetchEvidence}
            disabled={isLoadingEvidence}
            title="Refresh harvested evidence"
            style={{
              background: '#1e293b', color: '#94a3b8', border: '1px solid #334155',
              borderRadius: 6, padding: '7px 12px', fontSize: 12, fontWeight: 600,
              cursor: 'pointer', display: 'flex', alignItems: 'center', gap: 6
            }}
          >
            <RefreshCw size={14} className={isLoadingEvidence ? 'animate-spin' : ''} />
            Evidence ({evidencePackage?.total_evidence_count || 0})
          </button>

          <button
            onClick={handleGenerateReport}
            disabled={isGenerating}
            style={{
              background: '#0ea5e9', color: '#ffffff', border: 'none',
              borderRadius: 6, padding: '7px 16px', fontSize: 12, fontWeight: 700,
              cursor: isGenerating ? 'not-allowed' : 'pointer', display: 'flex', alignItems: 'center', gap: 6
            }}
          >
            {isGenerating ? <RefreshCw size={14} className="animate-spin" /> : <Award size={14} />}
            Generate Comprehensive Report
          </button>

          {report && (
            <>
              <button
                onClick={handleExportHtml}
                title="Download Standalone HTML"
                style={{
                  background: '#1e293b', color: '#f8fafc', border: '1px solid #334155',
                  borderRadius: 6, padding: '7px 12px', fontSize: 12, fontWeight: 600,
                  cursor: 'pointer', display: 'flex', alignItems: 'center', gap: 6
                }}
              >
                <Download size={14} /> Export HTML
              </button>

              <button
                onClick={handlePrint}
                title="Print or Save as PDF"
                style={{
                  background: '#1e293b', color: '#f8fafc', border: '1px solid #334155',
                  borderRadius: 6, padding: '7px 12px', fontSize: 12, fontWeight: 600,
                  cursor: 'pointer', display: 'flex', alignItems: 'center', gap: 6
                }}
              >
                <Printer size={14} /> Print / PDF
              </button>
            </>
          )}
        </div>
      </div>

      {/* Error Banner */}
      {errorMessage && (
        <div style={{
          padding: '8px 20px', background: '#450a0a', color: '#fca5a5',
          fontSize: 12, display: 'flex', alignItems: 'center', justifyContent: 'space-between',
          borderBottom: '1px solid #7f1d1d'
        }}>
          <span>{errorMessage}</span>
          <button onClick={() => setErrorMessage(null)} style={{ background: 'transparent', border: 'none', color: '#fca5a5', cursor: 'pointer' }}>×</button>
        </div>
      )}

      {/* Main Studio Body */}
      <div style={{ flex: 1, display: 'flex', overflow: 'hidden' }}>
        
        {/* Left Section Navigation */}
        <div style={{
          width: 260,
          background: '#0d1322',
          borderRight: '1px solid #1e293b',
          display: 'flex',
          flexDirection: 'column',
          flexShrink: 0
        }}>
          <div style={{ padding: '12px 16px', borderBottom: '1px solid #1e293b', fontSize: 11, fontWeight: 700, color: '#64748b', textTransform: 'uppercase' }}>
            Report Sections
          </div>

          <div style={{ flex: 1, overflowY: 'auto', padding: 8 }}>
            {sectionsList.map((sec) => {
              const Icon = sec.icon;
              const isSelected = selectedSection === sec.id;
              const secItem = report?.sections?.find(s => s.section_id === sec.id);
              const secText = secItem?.narrative || secItem?.content || '';
              const hasEvidence = secItem && typeof secText === 'string' && secText.length > 0 && !secText.includes('No verified');
              return (
                <div
                  key={sec.id}
                  onClick={() => setSelectedSection(sec.id)}
                  style={{
                    display: 'flex',
                    alignItems: 'center',
                    justifyContent: 'space-between',
                    padding: '8px 12px',
                    borderRadius: 6,
                    cursor: 'pointer',
                    background: isSelected ? '#1e293b' : 'transparent',
                    color: isSelected ? '#38bdf8' : '#e2e8f0',
                    fontSize: 12,
                    fontWeight: isSelected ? 700 : 500,
                    marginBottom: 3,
                    transition: 'all 0.15s ease'
                  }}
                  onMouseEnter={(e) => { if (!isSelected) e.currentTarget.style.background = '#151d30'; }}
                  onMouseLeave={(e) => { if (!isSelected) e.currentTarget.style.background = 'transparent'; }}
                >
                  <div style={{ display: 'flex', alignItems: 'center', gap: 8 }}>
                    <Icon size={14} color={isSelected ? '#38bdf8' : '#94a3b8'} />
                    <span>{sec.title}</span>
                  </div>
                  {hasEvidence && (
                    <CheckCircle2 size={12} color="#10b981" />
                  )}
                </div>
              );
            })}
          </div>

          {/* Provenance Badge in Sidebar */}
          {report && (
            <div style={{ padding: '12px 14px', borderTop: '1px solid #1e293b', background: '#0a0f1c', fontSize: 11, color: '#64748b' }}>
              <div>Generated: {new Date(report.generated_at).toLocaleTimeString()}</div>
              <div style={{ overflow: 'hidden', textOverflow: 'ellipsis', whiteSpace: 'nowrap' }}>
                FP: {report.dataset_fingerprint?.substring(0, 16)}...
              </div>
            </div>
          )}
        </div>

        {/* Center / Right Content Viewer */}
        <div style={{ flex: 1, overflowY: 'auto', padding: '24px 32px', background: '#090d16' }}>
          
          {/* Executive Summary & Key Findings Card */}
          {report ? (
            <div style={{
              background: '#0d1322',
              border: '1px solid #1e293b',
              borderRadius: 8,
              padding: 20,
              marginBottom: 24
            }}>
              <div style={{ fontSize: 16, fontWeight: 800, color: '#f8fafc', marginBottom: 8 }}>
                Executive Summary
              </div>
              <div style={{ fontSize: 13, lineHeight: 1.6, color: '#cbd5e1', marginBottom: 16 }}>
                {report.executive_summary}
              </div>

              {report.key_findings && report.key_findings.length > 0 && (
                <div>
                  <div style={{ fontSize: 12, fontWeight: 700, color: '#38bdf8', textTransform: 'uppercase', marginBottom: 8 }}>
                    Key Analytical Findings
                  </div>
                  <ul style={{ margin: 0, paddingLeft: 20, fontSize: 12, color: '#e2e8f0', lineHeight: 1.6 }}>
                    {report.key_findings.map((f, idx) => (
                      <li key={idx} style={{ marginBottom: 4 }}>{f}</li>
                    ))}
                  </ul>
                </div>
              )}
            </div>
          ) : (
            <div style={{
              background: '#0d1322',
              border: '1px solid #1e293b',
              borderRadius: 8,
              padding: 36,
              textAlign: 'center',
              marginBottom: 24
            }}>
              <FileText size={36} color="#334155" style={{ margin: '0 auto 12px auto' }} />
              <div style={{ fontSize: 15, fontWeight: 700, color: '#f8fafc', marginBottom: 6 }}>
                No Report Generated Yet
              </div>
              <div style={{ fontSize: 12, color: '#94a3b8', maxWidth: 440, margin: '0 auto 16px auto', lineHeight: 1.5 }}>
                Click <strong>Generate Comprehensive Report</strong> above to harvest verified findings across all completed analysis phases and DuckDB queries.
              </div>
              <button
                onClick={handleGenerateReport}
                disabled={isGenerating}
                style={{
                  background: '#0ea5e9', color: '#ffffff', border: 'none',
                  borderRadius: 6, padding: '8px 18px', fontSize: 12, fontWeight: 700,
                  cursor: 'pointer'
                }}
              >
                {isGenerating ? 'Generating Report...' : 'Generate Report Now'}
              </button>
            </div>
          )}

          {/* Selected Section Detail */}
          {report && currentSectionData ? (() => {
            const sectionNarrative = currentSectionData.narrative || currentSectionData.content || '';
            const sectionMetrics = currentSectionData.metrics || currentSectionData.key_metrics || {};
            const sectionTables = currentSectionData.tables || currentSectionData.table_data || [];
            const isVerified = currentSectionData.is_verified !== false;
            return (
              <div style={{
                background: '#0d1322',
                border: '1px solid #1e293b',
                borderRadius: 8,
                padding: 24
              }}>
                <div style={{ display: 'flex', alignItems: 'center', justifyContent: 'space-between', marginBottom: 16 }}>
                  <h3 style={{ margin: 0, fontSize: 16, fontWeight: 800, color: '#f8fafc' }}>
                    {currentSectionData.title}
                  </h3>
                  {isVerified && (
                    <span style={{
                      background: '#052e16', color: '#4ade80', fontSize: 11, fontWeight: 700,
                      padding: '2px 8px', borderRadius: 4, display: 'flex', alignItems: 'center', gap: 4
                    }}>
                      <ShieldCheck size={12} /> Scientifically Verified
                    </span>
                  )}
                </div>

                {/* Section Narrative */}
                <div style={{
                  fontSize: 13,
                  lineHeight: 1.6,
                  color: '#cbd5e1',
                  whiteSpace: 'pre-wrap',
                  fontFamily: 'inherit',
                  marginBottom: 20
                }}>
                  {sectionNarrative}
                </div>

                {/* Section Key Metrics Grid */}
                {sectionMetrics && Object.keys(sectionMetrics).length > 0 && (
                  <div style={{ marginBottom: 20 }}>
                    <div style={{ fontSize: 12, fontWeight: 700, color: '#38bdf8', textTransform: 'uppercase', marginBottom: 10 }}>
                      Extracted Metrics
                    </div>
                    <div style={{ display: 'grid', gridTemplateColumns: 'repeat(auto-fill, minmax(180px, 1fr))', gap: 10 }}>
                      {Object.entries(sectionMetrics).map(([k, v], idx) => (
                        <div key={idx} style={{
                          background: '#151d30',
                          border: '1px solid #222f49',
                          borderRadius: 6,
                          padding: '10px 14px'
                        }}>
                          <div style={{ fontSize: 11, color: '#94a3b8', textTransform: 'capitalize', marginBottom: 4 }}>
                            {k.replace(/_/g, ' ')}
                          </div>
                          <div style={{ fontSize: 15, fontWeight: 700, color: '#f8fafc', fontFamily: 'monospace' }}>
                            {typeof v === 'number' ? (Number.isInteger(v) ? v : v.toFixed(3)) : String(v)}
                          </div>
                        </div>
                      ))}
                    </div>
                  </div>
                )}

                {/* Data Table if present */}
                {sectionTables && sectionTables.length > 0 && (
                  <div>
                    <div style={{ fontSize: 12, fontWeight: 700, color: '#38bdf8', textTransform: 'uppercase', marginBottom: 10 }}>
                      Structured Observations
                    </div>
                    <div style={{ overflowX: 'auto', borderRadius: 6, border: '1px solid #1e293b' }}>
                      <table style={{ width: '100%', borderCollapse: 'collapse', fontSize: 12, textAlign: 'left' }}>
                        <thead>
                          <tr style={{ background: '#151d30', borderBottom: '1px solid #1e293b' }}>
                            {Object.keys(sectionTables[0] || {}).map((col, idx) => (
                              <th key={idx} style={{ padding: '8px 12px', color: '#e2e8f0', fontWeight: 700, fontFamily: 'monospace' }}>
                                {col}
                              </th>
                            ))}
                          </tr>
                        </thead>
                        <tbody>
                          {sectionTables.slice(0, 10).map((row, rIdx) => (
                            <tr key={rIdx} style={{ borderBottom: '1px solid #1e293b', background: rIdx % 2 === 0 ? '#0d1322' : '#090d16' }}>
                              {Object.values(row).map((val, cIdx) => (
                                <td key={cIdx} style={{ padding: '6px 12px', color: '#cbd5e1' }}>
                                  {String(val)}
                                </td>
                              ))}
                            </tr>
                          ))}
                        </tbody>
                      </table>
                    </div>
                  </div>
                )}
              </div>
            );
          })() : null}

        </div>
      </div>
    </div>
  );
}
